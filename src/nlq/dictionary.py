"""Generate docs/generated/metric_dictionary.md from the compiled semantic manifest.

The semantic YAML in rack-delivery-pipeline is the only place a metric is defined; this
dictionary is derived from it (via artifacts/semantic_manifest.json) and never edited by hand.
Output is deterministic: same manifest, same bytes.

    python -m nlq.dictionary
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "artifacts" / "semantic_manifest.json"
OUTPUT = ROOT / "docs" / "generated" / "metric_dictionary.md"
EXAMPLES = "examples"  # relative to OUTPUT

# The governance columns of docs/METRICS.md, in order: (header, metric meta key).
COLUMNS = [
    ("Formula", "formula"),
    ("Time anchor", "time_anchor"),
    ("Grain", "grain"),
    ("Source model", "source_model"),
    ("Owner", "owner"),
    ("Refresh SLA", "refresh_sla"),
    ("Exclusions", "exclusions"),
]


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _measures(manifest: dict[str, Any]) -> dict[str, tuple[str, dict[str, Any]]]:
    """measure name -> (semantic model name, measure)."""
    return {
        measure["name"]: (model["name"], measure)
        for model in manifest["semantic_models"]
        for measure in model["measures"]
    }


def _built_from(metric: dict[str, Any], measures: dict[str, tuple[str, dict[str, Any]]]) -> str:
    params = metric["type_params"]
    if metric["type"] == "ratio":
        return f"`{params['numerator']['name']}` / `{params['denominator']['name']}`"
    model, measure = measures[params["measure"]["name"]]
    agg = measure["agg"]
    if measure.get("agg_params") and measure["agg_params"].get("percentile") is not None:
        agg += f" {measure['agg_params']['percentile']}"
    return f"{agg} of `{measure['expr']}` in `{model}`"


def _dimensions(manifest: dict[str, Any]) -> list[str]:
    """Group-by dimensions reachable from the delivery fact, as entity__dimension."""
    names = ["metric_time"]
    for model in sorted(manifest["semantic_models"], key=lambda m: m["name"]):
        primary = [e["name"] for e in model["entities"] if e["type"] == "primary"]
        for dimension in model["dimensions"]:
            if dimension["type"] == "categorical":
                names.append(f"{primary[0]}__{dimension['name']}")
    return names


def render(manifest: dict[str, Any]) -> str:
    measures = _measures(manifest)
    metrics = sorted(manifest["metrics"], key=lambda m: m["name"])
    governed = [m for m in metrics if "component_of" not in m["config"]["meta"]]
    components = [m for m in metrics if "component_of" in m["config"]["meta"]]

    lines = [
        "# Metric dictionary",
        "",
        "Generated by `make dictionary` from `artifacts/semantic_manifest.json`, the compiled "
        "semantic layer of rack-delivery-pipeline (`dbt/models/semantic/`). Do not edit by "
        "hand: change the semantic YAML through the process in "
        "[GOVERNANCE.md](../GOVERNANCE.md), then regenerate.",
        "",
        '"Completed" means `production_at is not null`.',
        "",
        "## Governed metrics",
        "",
        "| Metric | Definition | " + " | ".join(h for h, _ in COLUMNS) + " |",
        "|" + "---|" * (len(COLUMNS) + 2),
    ]
    for metric in governed:
        meta = metric["config"]["meta"]
        cells = [f"`{metric['name']}`", _cell(metric["description"])]
        cells += [_cell(meta.get(key, "")) for _, key in COLUMNS]
        lines.append("| " + " | ".join(cells) + " |")

    lines += ["", "## How each metric is computed", ""]
    for metric in governed + components:
        lines += [
            f"### {metric['label']} (`{metric['name']}`)",
            "",
            _cell(metric["description"]),
            "",
            f"- Type: {metric['type']}",
            f"- Built from: {_built_from(metric, measures)}",
        ]
        if "component_of" in metric["config"]["meta"]:
            lines.append(
                f"- Component of `{metric['config']['meta']['component_of']}` (a ratio metric "
                "can only reference metrics); not reported on its own."
            )
        else:
            lines.append(
                f"- Canonical query: [{metric['name']}.sql]({EXAMPLES}/{metric['name']}.sql)"
            )
        lines.append("")

    lines += [
        "## Dimensions",
        "",
        "Every metric can be grouped or filtered by:",
        "",
        *[f"- `{name}`" for name in _dimensions(manifest)],
        "",
        "`metric_time` is each metric's time anchor (for example `production_at` for "
        "`on_time_delivery_rate`). `racks_in_flight` and `overdue_open_racks` describe the "
        "current state; grouping them by `metric_time` splits them by order date.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    OUTPUT.write_text(render(manifest), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
